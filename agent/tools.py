# ─────────────────────────────────────────
#  Shell tool
# ─────────────────────────────────────────
# Recursive scans over the SMB mount (the PC's whole C: drive) or over the
# entire home directory can run for minutes, blow the tool budget and return
# nothing useful. Detect them and cap the wall clock instead of hanging.
_HEAVY_SCAN_RE = re.compile(r"(\bgrep\b[^|;]*\s-[a-zA-Z]*[rR]|\bfind\s+[^|;]*|\bdu\s+-[a-zA-Z]*s|\bzip\s+-r)",
                            re.IGNORECASE)
_HEAVY_ROOTS = ("/mnt/share", "/mnt/", "/media/", "/home/pi", "~/", "/")
HEAVY_SCAN_TIMEOUT = 25


def _heavy_scan(command: str) -> bool:
    """True when the command walks a huge tree recursively without a narrow scope."""
    cmd = command or ""
    if not _HEAVY_SCAN_RE.search(cmd):
        return False
    if "maxdepth" in cmd or "--include" in cmd:
        return False
    return any(root in cmd for root in _HEAVY_ROOTS)


def tool_shell(command: str, timeout: int = 120) -> str:
    """Run a shell command. Returns stdout+stderr."""

    # Restarting the server from inside a turn kills the turn: the reply the
    # user is already reading only lives in memory, and anything queued dies
    # with the process. Accept the request and let the hub restart the moment
    # this turn is over (and its message is stored) instead.
    try:
        from store import restart as _restart_mod
        if _restart_mod.is_restart_command(command):
            return _restart_mod.defer(command)
    except Exception:
        logger.warning("restart guard failed", exc_info=True)

    # check command history before running
    history = lookup_command(command)
    if history:
        status = history["status"]
        prev   = history["command"]
        ts     = history["ts"]
        reason = history.get("reason", "")
        note = f"[history] '{prev}' was {status} on {ts}"
        if reason:
            note += f" — {reason}"
        _emit(note)
        # prepend note to output so LLM sees it
        history_note = note
    else:
        history_note = ""

    if _is_dangerous(command):
        if _confirm_callback:
            confirmed = _confirm_callback(
                f"⚠️ *Dangerous command detected:*\n`{command}`\n\nConfirm? (yes/no)"
            )
            if not confirmed:
                return "Cancelled by user."
        else:
            return f"BLOCKED: dangerous command requires confirmation — {command}"

    if _heavy_scan(command):
        if timeout > HEAVY_SCAN_TIMEOUT:
            _emit(f"[guard] recursive scan over a big tree, timeout capped to {HEAVY_SCAN_TIMEOUT}s")
            timeout = HEAVY_SCAN_TIMEOUT

    _emit(f"$ {command}")

    try:
        # PTY-style read so programs that line-buffer to a tty (apt, pip, etc.)
        # still produce live output, and CR-based progress lines come through.
        import pty, select, errno
        master_fd, slave_fd = pty.openpty()
        proc = subprocess.Popen(
            command, shell=True,
            stdin=slave_fd, stdout=slave_fd, stderr=slave_fd,
            preexec_fn=os.setsid, close_fds=True,
        )
        os.close(slave_fd)

        output_chunks = []
        buf = ""
        start = time.time()
        try:
            while True:
                if proc.poll() is not None and not _has_data(master_fd):
                    break
                if _cancelled():
                    try:
                        os.killpg(os.getpgid(proc.pid), 9)
                    except Exception:
                        pass
                    return "CANCELLED by the user"
                if time.time() - start > timeout:
                    try:
                        os.killpg(os.getpgid(proc.pid), 9)
                    except Exception:
                        pass
                    log_command(command, False, reason="timeout")
                    return f"TIMEOUT after {timeout}s"
                r, _, _ = select.select([master_fd], [], [], 0.2)
                if master_fd not in r:
                    continue
                try:
                    chunk = os.read(master_fd, 4096)
                except OSError as e:
                    if e.errno == errno.EIO:
                        break
                    raise
                if not chunk:
                    break
                text = chunk.decode("utf-8", errors="replace")
                output_chunks.append(text)
                # split on either CR or LF so progress bars come through
                buf += text.replace("\r", "\n")
                while "\n" in buf:
                    line, buf = buf.split("\n", 1)
                    if line:
                        _emit(line)
            if buf:
                _emit(buf)
        finally:
            try: os.close(master_fd)
            except Exception: pass
        proc.wait(timeout=5)
        output = "".join(output_chunks)
        # strip carriage returns for the final string handed to the LLM
        output = re.sub(r"\r(?!\n)", "\n", output).strip()
        success = proc.returncode == 0

        log_command(command, success, output[:500],
                    reason="" if success else f"exit code {proc.returncode}")

        result = output or "[command completed with no output]"
        if history_note:
            result = history_note + "\n" + result
        if not success:
            return f"[exit {proc.returncode}]\n{result}"
        return result

    except Exception as e:
        log_command(command, False, reason=str(e))
        return f"ERROR: {e}"


def _has_data(fd: int) -> bool:
    try:
        import select as _s
        r, _, _ = _s.select([fd], [], [], 0)
        return fd in r
    except Exception:
        return False

