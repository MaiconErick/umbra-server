def tool_browser(action: str, url: str = "", selector: str = "",
                  text: str = "", wait: int = 3) -> str:
    try:
        from selenium import webdriver
        from selenium.webdriver.chrome.options import Options
        from selenium.webdriver.common.by import By
        from selenium.webdriver.support.ui import WebDriverWait
        from selenium.webdriver.support import expected_conditions as EC
    except ImportError:
        return "Selenium not installed. Run: pip install selenium"

    vivaldi_path = "/usr/bin/vivaldi-stable"
    if not os.path.exists(vivaldi_path):
        return f"Vivaldi not found at {vivaldi_path}"

    options = Options()
    options.binary_location = vivaldi_path
    options.add_argument("--headless=new")
    options.add_argument("--no-sandbox")
    options.add_argument("--disable-dev-shm-usage")

    try:
        driver = webdriver.Chrome(options=options)

        if action == "open":
            driver.get(url)
            time.sleep(wait)
            result = f"Opened: {url}\nTitle: {driver.title}"
        elif action == "scrape":
            driver.get(url)
            time.sleep(wait)
            result = driver.find_element(By.TAG_NAME, "body").text[:3000]
        elif action == "screenshot":
            driver.get(url)
            time.sleep(wait)
            path = os.path.join(TEMP_DIR, f"screenshot_{int(time.time())}.png")
            driver.save_screenshot(path)
            result = f"Screenshot saved: {path}"
        elif action == "click":
            el = WebDriverWait(driver, wait).until(
                EC.element_to_be_clickable((By.CSS_SELECTOR, selector))
            )
            el.click()
            result = f"Clicked: {selector}"
        elif action == "type":
            el = driver.find_element(By.CSS_SELECTOR, selector)
            el.send_keys(text)
            result = f"Typed into {selector}"
        else:
            result = f"Unknown action: {action}"

        driver.quit()
        return result
    except Exception as e:
        return f"Browser error: {e}"

