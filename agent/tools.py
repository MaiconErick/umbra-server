_KNOWN_IMAGE_PROVIDERS = {"openai", "openrouter", "gemini", "code"}

# Casual model nicknames the model (Muse) can pass as `model=`. If Maicon says
# "do this with nano banana", Muse can pass model="nano-banana" verbatim and
# the tool resolves it to the actual model id + provider. Keys are lowercased,
# non-alphanumeric stripped. Value is (provider, real_model_id).
#
# Preference: when a nickname is available on multiple providers (e.g. gemini
# direct + openrouter), we prefer the direct provider — cheaper, no extra hop.
_MODEL_ALIASES: dict[str, tuple[str, str]] = {
    # Gemini direct (preferred over openrouter for the same model)
    "nanobanana":                 ("gemini",     "gemini-2.5-flash-image"),
    "gemini25flashimage":         ("gemini",     "gemini-2.5-flash-image"),
    "gemini3proimage":            ("gemini",     "gemini-3-pro-image"),
    "gemini31flashimage":         ("gemini",     "gemini-3.1-flash-image"),
    "gemini31flashliteimage":     ("gemini",     "gemini-3.1-flash-lite-image"),
    # OpenAI direct
    "gptimage":                   ("openai",     "gpt-image-1"),
    "gptimage1":                  ("openai",     "gpt-image-1"),
    "dalle":                      ("openai",     "dall-e-3"),
    "dalle3":                     ("openai",     "dall-e-3"),
    # OpenRouter — proxied openai + others (unique to openrouter)
    "gpt5image":                  ("openrouter", "openai/gpt-5-image"),
    "gpt5imagemini":              ("openrouter", "openai/gpt-5-image-mini"),
    "gpt54image2":                ("openrouter", "openai/gpt-5.4-image-2"),
}


def _resolve_alias(name: str) -> tuple[str, str] | None:
    if not name:
        return None
    key = "".join(c for c in name.lower() if c.isalnum())
    return _MODEL_ALIASES.get(key)


def tool_generate_image(prompt: str, provider: str = None,
                        model: str = None, references: list | None = None) -> str:
    """Generate an image. Two provider paths:

    - openai      -> /v1/images/generations with e.g. gpt-image-1 or dall-e-3
    - openrouter  -> /v1/chat/completions with modalities=[image,text] using an
                     image-capable model (google/gemini-2.5-flash-image, etc).
                     Response returns a base64 data URL inside message.images.

    Args:
      prompt:   image description.
      provider: "openai" | "openrouter" | (blank = config default).
      model:    override the image model. Accepts full ids ("google/gemini-2.5-
                flash-image", "openai/gpt-image-1") OR casual nicknames from
                _MODEL_ALIASES ("nano-banana", "gpt-image", "dall-e-3", …).
                A nickname also implies the provider — no need to pass both.
    """
    import configparser, requests as req, base64
    cfg = configparser.ConfigParser()
    cfg.read(os.path.join(BASE_DIR, "config.ini"))

    # Role assignments win over config.ini, so the Settings UI can override
    # without touching disk-config.
    try:
        from agent.model_roles import get_role
        role = get_role("image_gen") or {}
    except Exception:
        role = {}

    default_prov  = role.get("provider") or cfg.get("image", "provider", fallback="openai")
    default_model = role.get("model")    or cfg.get("image", "model",    fallback="gpt-image-1")

    # If this call came from a chat that has a picked default_image_model in
    # its chat_meta (set via the app's dropdown), use that as the default.
    # Explicit `model=` from the tool call still wins over it below.
    if not (model or "").strip() and get_current_sid():
        try:
            from store.manager import get_chat_meta
            picked = (get_chat_meta(get_current_sid()).get("default_image_model") or "").strip()
        except Exception:
            picked = ""
        if picked:
            model = picked

    # 1) If model= is a casual nickname it implies the provider — resolve both.
    alias = _resolve_alias(model)
    if alias:
        prov, chosen_model = alias
    else:
        # 2) Otherwise use provider as-given; unknown provider strings from the
        # LLM silently fall back to the configured default.
        prov = (provider or "").lower().strip()
        if prov not in _KNOWN_IMAGE_PROVIDERS:
            prov = default_prov
        chosen_model = (model or "").strip()
        # 3) Infer provider from the shape of the model id when possible:
        #    - `org/name`      -> openrouter
        #    - `gemini-*-image` (bare) -> gemini direct
        #    - `gpt-image*` / `dall-e*` (bare) -> openai
        # This means a caller who only says `model="gemini-3-pro-image"` or
        # `model="google/gemini-2.5-flash-image"` still lands on the right side.
        if chosen_model:
            if chosen_model.startswith("code/"):
                prov = "code"
            elif "/" in chosen_model:
                prov = "openrouter"
            elif chosen_model.startswith(("gemini-", "imagen-")):
                prov = "gemini"
            elif chosen_model.startswith(("gpt-image", "dall-e")):
                prov = "openai"
        else:
            chosen_model = default_model
    model = chosen_model
    if model.startswith("code/"):
        prov = "code"
    elif model.startswith(("gemini-", "nano-banana")) and prov not in ("gemini", "openrouter"):
        prov = "gemini"
    size  = cfg.get("image", "size",  fallback="1024x1024")

    out_path = os.path.join(TEMP_DIR, f"image_{int(time.time())}.png")
    from agent import imagegen
    sid = get_current_sid()
    _t0 = time.time()
    quality = cfg.get("image", "quality", fallback="medium")
    refs = [r for r in (references or []) if r and os.path.exists(r)][:4]
    _img_progress(stage="start", provider=prov, model=model, name=imagegen.display_name(model),
                  expected=imagegen.expected_secs(prov, model), refs=len(refs))

    def _mime(path):
        e = path.rsplit(".", 1)[-1].lower()
        return {"jpg": "image/jpeg", "jpeg": "image/jpeg", "webp": "image/webp", "gif": "image/gif"}.get(e, "image/png")

    def _b64(path):
        with open(path, "rb") as fh:
            return base64.b64encode(fh.read()).decode()

    # dall-e can't take a reference picture → the newest gpt-image edits instead
    if refs and prov == "openai" and model.startswith("dall-e"):
        model = "gpt-image-1.5"
    # Reset the sidecar so a failed generation doesn't leave stale meta.
    _tls.last_image_meta = None
    try:
        from openai import OpenAI
        if prov == "openai":
            client = OpenAI(api_key=os.getenv("OPENAI_API_KEY"))
            kw = {"quality": quality} if model.startswith("gpt-image") else {}
            stream_kw = {"stream": True, "partial_images": 2} if model.startswith("gpt-image") else {}
            try:
                if refs:
                    files = [open(r, "rb") for r in refs]
                    try:
                        response = client.images.edit(model=model, image=files if len(files) > 1 else files[0],
                                                      prompt=prompt, size=size, **kw, **stream_kw)
                    finally:
                        if not stream_kw:
                            for fh in files:
                                fh.close()
                else:
                    response = client.images.generate(
                        model=model, prompt=prompt, size=size, n=1, **kw, **stream_kw
                    )
                if stream_kw:
                    # partial previews arrive first, then the finished picture (with usage)
                    final = None
                    for ev in response:
                        et = getattr(ev, "type", "")
                        if et.endswith("partial_image"):
                            pn = _save_partial(getattr(ev, "b64_json", "") or "")
                            if pn:
                                _img_progress(stage="partial", partial=pn, index=getattr(ev, "partial_image_index", 0))
                        elif et.endswith("completed"):
                            final = ev
                    if refs:
                        for fh in files:
                            fh.close()
                    if final is None:
                        return "Image generation error: the stream ended without a picture"
                    response = type("R", (), {"data": [final], "usage": getattr(final, "usage", None)})()
            except Exception as e:
                # OpenAI refuses some things Gemini draws fine (e.g. Pokémon fan art) —
                # retry there once instead of making the chat model call again.
                if "safety" in str(e).lower() or "moderation" in str(e).lower():
                    first = imagegen.display_name(model)
                    _img_progress(stage="fallback", from_name=first, to_name="Nano Banana 2.1",
                                  reason="OpenAI's safety filter")
                    r2 = tool_generate_image(prompt, model="gemini-nano-banana-2.1", references=refs)
                    if not str(r2).startswith("Image generation error") and _tls.last_image_meta:
                        _tls.last_image_meta["note"] = (f"{first} refused this (OpenAI's safety filter — it blocks things "
                                                        f"like Pokémon fan art), so Nano Banana 2.1 drew it instead.")
                    return r2
                raise
            data0 = response.data[0]
            # gpt-image-1 returns b64_json by default; dall-e-3 returns url.
            img_data = None
            b64 = getattr(data0, "b64_json", None)
            if b64:
                img_data = base64.b64decode(b64)
            else:
                url = getattr(data0, "url", None)
                if url:
                    img_data = req.get(url, timeout=30).content
            if not img_data:
                return "Image generation error: response had no image payload"
            with open(out_path, "wb") as f:
                f.write(img_data)
            cost = imagegen.openai_cost(model, getattr(response, "usage", None))
            imagegen.record("openai", model, cost, prompt, sid, time.time() - _t0)
            _tls.last_image_meta = {"path": out_path, "provider": "openai", "model": model, "cost": round(cost, 6)}
            return out_path

        elif prov == "openrouter":
            # OpenRouter image models use chat.completions with an image
            # modality on the output. The default here is a fast Google model;
            # override via config.ini [image] model = <openrouter model id>.
            or_model = model
            # Sensible default when the config still points at an openai model
            # id (config.ini defaults are shared with the openai path).
            if or_model.startswith("gpt-image") or or_model.startswith("dall-e"):
                or_model = "google/gemini-2.5-flash-image"
            client = OpenAI(
                base_url="https://openrouter.ai/api/v1",
                api_key=os.getenv("OPENROUTER_API_KEY"),
            )
            resp = client.chat.completions.create(
                model=or_model,
                modalities=["image", "text"],
                messages=[{"role": "user", "content": ([{"type": "text", "text": prompt}] + [
                    {"type": "image_url", "image_url": {"url": f"data:{_mime(r)};base64,{_b64(r)}"}} for r in refs])
                    if refs else prompt}],
                extra_body={"usage": {"include": True}},
            )
            msg = resp.choices[0].message
            # OpenRouter returns `message.images = [{image_url: {url: "data:image/png;base64,..."}}]`
            images = getattr(msg, "images", None) or []
            img_data = None
            for it in images:
                iu = (it.get("image_url") or {}).get("url") if isinstance(it, dict) else \
                     getattr(getattr(it, "image_url", None), "url", None)
                if not iu:
                    continue
                if iu.startswith("data:"):
                    _, b64 = iu.split(",", 1)
                    img_data = base64.b64decode(b64)
                else:
                    img_data = req.get(iu, timeout=30).content
                if img_data:
                    break
            if not img_data:
                return (f"Image generation error: openrouter model '{or_model}' "
                        f"returned no image payload (check the model supports image output)")
            with open(out_path, "wb") as f:
                f.write(img_data)
            cost = imagegen.openrouter_cost(getattr(resp, "usage", None))
            if cost is None:
                cost = 0.0
            imagegen.record("openrouter", or_model, cost, prompt, sid, time.time() - _t0)
            _tls.last_image_meta = {"path": out_path, "provider": "openrouter", "model": or_model, "cost": round(cost, 6)}
            return out_path

        elif prov == "code":
            c_model = model.split("/", 1)[1] if model.startswith("code/") else model
            path, cost, err = imagegen.code_art(prompt, c_model, out_path, refs, progress=_img_progress)
            imagegen.record("openrouter", "code/" + c_model, cost, prompt, sid, time.time() - _t0)
            if not path:
                return f"Image generation error: code art failed — {err[-400:]}"
            _tls.last_image_meta = {"path": out_path, "provider": "code", "model": "code/" + c_model, "cost": round(cost, 6)}
            return out_path

        elif prov == "gemini":
            # Gemini direct API — image-capable models use generateContent
            # with `responseModalities: ["IMAGE"]`. Cheaper than the same
            # model through OpenRouter (no middleman markup).
            g_model = model
            if g_model.startswith("gpt-image") or g_model.startswith("dall-e"):
                g_model = "gemini-2.5-flash-image"
            g_model = g_model.split("/", 1)[-1]  # strip any "google/" prefix
            api_key = os.getenv("GEMINI_API_KEY")
            if not api_key:
                return "Image generation error: GEMINI_API_KEY not set"
            url = (f"https://generativelanguage.googleapis.com/v1beta/"
                   f"models/{g_model}:generateContent?key={api_key}")
            body = {
                "contents": [{"role": "user",
                              "parts": [{"inlineData": {"mimeType": _mime(r), "data": _b64(r)}} for r in refs]
                                       + [{"text": prompt}]}],
                "generationConfig": {"responseModalities": ["IMAGE"]},
            }
            r = req.post(url, json=body, timeout=120)
            if r.status_code >= 400:
                return f"Image generation error: gemini {r.status_code} - {r.text[:400]}"
            j = r.json()
            img_data = None
            for cand in j.get("candidates", []):
                for part in ((cand.get("content") or {}).get("parts") or []):
                    inline = part.get("inlineData") or part.get("inline_data")
                    if inline and inline.get("data"):
                        img_data = base64.b64decode(inline["data"])
                        break
                if img_data:
                    break
            if not img_data:
                return (f"Image generation error: gemini model '{g_model}' "
                        f"returned no image payload")
            with open(out_path, "wb") as f:
                f.write(img_data)
            cost = imagegen.gemini_cost(g_model, j.get("usageMetadata"))
            imagegen.record("gemini", g_model, cost, prompt, sid, time.time() - _t0)
            _tls.last_image_meta = {"path": out_path, "provider": "gemini", "model": g_model, "cost": round(cost, 6)}
            return out_path

    except Exception as e:
        return f"Image generation error: {e}"
    return f"Image provider '{prov}' not configured yet"


def _img_done(out):
    if str(out).startswith("Image generation error"):
        _img_progress(stage="error", error=str(out)[24:200])
    else:
        m = _tls.last_image_meta or {}
        _img_progress(stage="done", cost=m.get("cost"), note=m.get("note"))


def _note_refs(n: int):
    if _tls.last_image_meta is not None and n:
        _tls.last_image_meta["references"] = n

