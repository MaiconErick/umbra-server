# Thread-local: each chat turn runs on its own thread, so two chats running
# at once no longer stream their shell output into each other's bubbles.
import threading as _threading
_tls = _threading.local()

_global_output_callback = None   # legacy (Telegram handler sets it from its event loop)

def set_output_callback(fn):
    """Legacy process-wide sink, used when the running thread has no own sink."""
    global _global_output_callback
    _global_output_callback = fn

def set_thread_output_callback(fn):
    """Sink for the calling thread only (xUmbra hub turns)."""
    _tls.output_callback = fn

def get_output_callback():
    return getattr(_tls, "output_callback", None) or _global_output_callback

def set_cancel_check(fn):
    """fn() -> bool; long-running tools poll it and stop early when True."""
    _tls.cancel_check = fn

def _cancelled() -> bool:
    fn = getattr(_tls, "cancel_check", None)
    try:
        return bool(fn and fn())
    except Exception:
        return False

def _emit(line: str):
    cb = get_output_callback()
    if cb:
        try:
            cb(line)
        except Exception:
            pass

