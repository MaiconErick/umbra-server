def tool_system_snapshot() -> str:
    """Quick system health check — RAM, disk, load, IP, uptime."""
    saved = getattr(_tls, "output_callback", None)
    _tls.output_callback = lambda _l: None  # silence output during snapshot

    lines = []
    r = tool_shell("free -h | awk '/^Mem/{print $2, $3, $7}'")
    lines.append(f"RAM (total/used/free): {r.strip()}")
    r = tool_shell("df -h / | awk 'NR==2{print $2, $3, $4}'")
    lines.append(f"Disk /  (total/used/free): {r.strip()}")
    r = tool_shell("cat /proc/loadavg | awk '{print $1, $2, $3}'")
    lines.append(f"Load avg (1/5/15m): {r.strip()}")
    r = tool_shell("hostname -I | awk '{print $1}'")
    lines.append(f"IP: {r.strip()}")
    r = tool_shell("uptime -p")
    lines.append(f"Uptime: {r.strip()}")

    _tls.output_callback = saved
    return "\n".join(lines)

