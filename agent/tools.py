def _build_compact_schema(tools: list) -> list:
    """Strip parameter descriptions and shorten tool descriptions.
    Used for LLM API calls to save tokens. TOOL_DEFINITIONS stays verbose for the inspector.
    """
    out = []
    for t in tools:
        fn = dict(t.get("function", {}))
        name = fn.get("name", "")
        desc = _COMPACT_DESCRIPTIONS.get(name) or fn.get("description", "")
        # fallback: truncate at first period within 120 chars
        if name not in _COMPACT_DESCRIPTIONS and len(desc) > 120:
            cut = desc[:120].rfind(".")
            desc = desc[: cut + 1] if cut > 0 else desc[:120]
        fn = {**fn, "description": desc}
        params = fn.get("parameters", {})
        if "properties" in params:
            stripped = {
                # `say` keeps its description: it is the instruction that makes
                # the model write a proper one-line intro for the app bubble.
                k: dict(v) if k == "say" else {kk: vv for kk, vv in v.items() if kk != "description"}
                for k, v in params["properties"].items()
            }
            fn = {**fn, "parameters": {**params, "properties": stripped}}
        out.append({"type": t.get("type", "function"), "function": fn})
    return out


