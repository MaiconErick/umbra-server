def tool_write_file(path: str, content: str) -> str:
    if os.path.exists(path):
        backup_name = f"{os.path.basename(path)}.{datetime.now().strftime('%Y%m%d_%H%M%S')}.bak"
        backup_path = os.path.join(BACKUPS_DIR, backup_name)
        shutil.copy2(path, backup_path)
        _emit(f"Backup created: {backup_path}")

    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w") as f:
        f.write(content)
    return f"Written: {path}"

def tool_read_file(path: str, offset: int = 1, limit: int = 0) -> str:
    """Read a file, or a window of it.

    Without offset/limit a big file only comes back as its start and end (the
    tool result is capped), so the window matters for anything large: read
    lines 1-150, then 151-300, and so on. Line numbers are NOT added to the
    text — copy a snippet straight into edit_file.
    """
    if not os.path.exists(path):
        return f"File not found: {path}"
    try:
        with open(path, "rb") as f:
            header = f.read(512)
        if b"\x00" in header:
            size = os.path.getsize(path)
            return f"[Binary file: {os.path.basename(path)}, {size:,} bytes — use shell to process]"
        with open(path, encoding="utf-8", errors="replace") as f:
            lines = f.read().splitlines()
    except Exception as e:
        return f"Error reading file: {e}"

    total = len(lines)
    try:
        start = max(1, int(offset or 1))
    except (TypeError, ValueError):
        start = 1
    try:
        count = int(limit or 0)
    except (TypeError, ValueError):
        count = 0

    if start > total:
        return f"[{path} has {total} lines — offset {start} is past the end]"
    if count > 0:
        end = min(total, start - 1 + count)
    else:
        # No window asked for: return as much as fits in one tool result
        # (~10k chars) instead of letting the cap cut the middle out.
        end, room = start - 1, 0
        while end < total and end - (start - 1) < 400 and room < 10000:
            room += len(lines[end]) + 1
            end += 1

    body = "\n".join(lines[start - 1:end])
    head = f"[{path}: lines {start}-{end} of {total}]"
    if end < total:
        head += f" — more below, call read_file with offset={end + 1}"
    return head + "\n" + body

def tool_list_dir(path: str) -> str:
    if not os.path.exists(path):
        return f"Path not found: {path}"
    entries = []
    for entry in sorted(os.scandir(path), key=lambda e: (not e.is_dir(), e.name)):
        kind = "DIR" if entry.is_dir() else "FILE"
        size = f"{entry.stat().st_size:,}B" if entry.is_file() else ""
        entries.append(f"[{kind}] {entry.name} {size}")
    return "\n".join(entries) or "(empty)"

# ─────────────────────────────────────────
#  Coding tools: exact edits, search, project runs
# ─────────────────────────────────────────
_SKIP_DIRS = {".git", ".hg", ".svn", ".gradle", ".kotlin", ".idea", "build", "node_modules",
              "venv", ".venv", "__pycache__", "dist", "target", ".next", "out", "obj", "Pods",
              ".dart_tool", "vendor"}
_MAX_EDIT_BYTES = 8 * 1024 * 1024


def _backup_before_edit(path: str) -> None:
    """Same safety net write_file gives: a timestamped copy in BACKUPS_DIR."""
    try:
        if not os.path.exists(path):
            return
        name = f"{os.path.basename(path)}.{datetime.now().strftime('%Y%m%d_%H%M%S')}.bak"
        os.makedirs(BACKUPS_DIR, exist_ok=True)
        shutil.copy2(path, os.path.join(BACKUPS_DIR, name))
        _emit(f"Backup created: {name}")
    except Exception as e:
        logger.warning(f"edit backup failed for {path}: {e}")


def _near_miss(text: str, needle: str) -> str:
    first = ((needle or "").strip().split("\n") or [""])[0][:60]
    if first:
        hits = [i + 1 for i, ln in enumerate(text.splitlines()) if first in ln][:3]
        if hits:
            return f" (a similar line is at line {hits})"
    stripped = "\n".join(ln.rstrip() for ln in text.splitlines())
    if needle.strip() and needle.strip() in stripped:
        return " (it exists, but indentation or trailing spaces differ)"
    return ""


def tool_edit_file(path: str, old_string: str, new_string: str = "",
                   replace_all: bool = False) -> str:
    """Replace one exact snippet inside a file.

    This is how a big file gets patched: write_file needs the whole content and
    read_file truncates, so before this tool the only way into a 200 KB file
    was `sed` by line number, which breaks as soon as a line moves.
    """
    if not os.path.exists(path):
        return f"File not found: {path}"
    if not old_string:
        return "ERROR: old_string is empty — use write_file to create a file."
    try:
        if os.path.getsize(path) > _MAX_EDIT_BYTES:
            return f"ERROR: {path} is larger than 8 MB — edit it with python instead."
        with open(path, encoding="utf-8", errors="replace") as f:
            text = f.read()
    except Exception as e:
        return f"ERROR reading {path}: {e}"

    count = text.count(old_string)
    if count == 0:
        return (f"ERROR: old_string not found in {path}{_near_miss(text, old_string)}. "
                f"Read the file again and copy the snippet exactly, indentation included.")
    if count > 1 and not replace_all:
        first = old_string.split("\n")[0].strip()
        lines = [str(i + 1) for i, ln in enumerate(text.splitlines()) if first and first in ln][:5]
        where = f" (first at line {', '.join(lines)})" if lines else ""
        return (f"ERROR: old_string appears {count} times in {path}{where}. "
                f"Include more surrounding lines so it is unique, or pass replace_all=true.")

    new_text = text.replace(old_string, new_string) if replace_all else text.replace(old_string, new_string, 1)
    _backup_before_edit(path)
    try:
        tmp = path + ".tmp_edit"
        with open(tmp, "w", encoding="utf-8") as f:
            f.write(new_text)
        os.replace(tmp, path)
    except Exception as e:
        return f"ERROR writing {path}: {e}"

    done = count if replace_all else 1
    idx = new_text.find(new_string) if new_string else new_text.find(old_string)
    line_no = (new_text[:idx].count("\n") + 1) if idx >= 0 else 0
    span = max(1, (new_string.count("\n") + 1)) if new_string else 1
    lines = new_text.splitlines()
    start, end = max(0, line_no - 3), min(len(lines), line_no + span + 1)
    snippet = "\n".join(f"{i + 1:>4} | {lines[i]}" for i in range(start, end))
    return f"Edited {path}: {done} replacement{'s' if done != 1 else ''}.\n{snippet}"


def _iter_files(path: str, globs: list[str], max_files: int = 4000):
    """Walk text files under path, skipping build/vendor folders."""
    seen = 0
    for root, dirs, names in os.walk(path):
        dirs[:] = [d for d in dirs if d not in _SKIP_DIRS and not d.startswith(".")]
        for name in sorted(names):
            if globs and not any(fnmatch.fnmatch(name, g) for g in globs):
                continue
            seen += 1
            if seen > max_files:
                return
            yield os.path.join(root, name)


def tool_grep(pattern: str, path: str = ".", include: str = "", ignore_case: bool = False,
              limit: int = 60) -> str:
    """Search file contents; prints file:line: text.

    `shell grep -r` over /mnt/share is slow and the scan guard cuts it off;
    this walks the tree in Python, skips build/vendor dirs and stops at the
    limit, so it stays quick on the Pi.
    """
    if not os.path.exists(path):
        return f"Path not found: {path}"
    try:
        rx = re.compile(pattern, re.IGNORECASE if ignore_case else 0)
    except re.error:
        rx = re.compile(re.escape(pattern), re.IGNORECASE if ignore_case else 0)
    globs = [g.strip() for g in (include or "").split(",") if g.strip()]
    hits: list[str] = []
    stop = ""
    t0 = time.monotonic()
    for full in _iter_files(path, globs):
        if time.monotonic() - t0 > 25:
            stop = "stopped after 25 s"
            break
        try:
            if os.path.getsize(full) > 2 * 1024 * 1024:
                continue
            with open(full, "rb") as f:
                if b"\x00" in f.read(512):
                    continue
            with open(full, encoding="utf-8", errors="replace") as f:
                for n, line in enumerate(f, 1):
                    if rx.search(line):
                        hits.append(f"{full}:{n}: {line.strip()[:200]}")
                        if len(hits) >= limit:
                            stop = f"stopped at {limit} matches"
                            break
        except Exception:
            continue
        if stop:
            break
    if not hits:
        return f"No matches for {pattern!r} under {path}" + (f" ({stop})" if stop else "")
    out = "\n".join(hits)
    return out + (f"\n… {stop}" if stop else "")


def tool_glob(pattern: str, path: str = ".", limit: int = 200) -> str:
    """Find files by name pattern (* and ? per path segment), newest first."""
    if not os.path.exists(path):
        return f"Path not found: {path}"
    pat = pattern or "*"
    found: list[tuple[float, str]] = []
    t0 = time.monotonic()
    for full in _iter_files(path, []):
        if time.monotonic() - t0 > 20:
            break
        if fnmatch.fnmatch(os.path.basename(full), pat):
            try:
                found.append((os.path.getmtime(full), full))
            except OSError:
                pass
        if len(found) > limit * 4:
            break
    if not found:
        return f"No files matching {pat} under {path}"
    found.sort(reverse=True)
    out = "\n".join(p for _, p in found[:limit])
    if len(found) > limit:
        out += f"\n… {len(found)} matches, showing the {limit} newest"
    return out


JOBS_DIR = os.path.join(TEMP_DIR, "jobs")
_jobs: dict[str, dict] = {}
_jobs_lock = threading.Lock()


def _prune_jobs(max_age: float = 3600) -> None:
    now = time.time()
    with _jobs_lock:
        for jid, j in list(_jobs.items()):
            if j["proc"].poll() is not None and now - j["started"] > max_age:
                try:
                    j["fp"].close()
                except Exception:
                    pass
                _jobs.pop(jid, None)
                try:
                    os.remove(j["log"])
                except OSError:
                    pass


def tool_jobs(op: str = "list", command: str = "", job_id: str = "", tail: int = 80) -> str:
    """Long commands in the background, so a build does not freeze the reply.

    start → returns an id; output → the log tail and whether it is still
    running; list → everything; kill → SIGTERM the process group.
    """
    os.makedirs(JOBS_DIR, exist_ok=True)
    op = (op or "list").lower()
    _prune_jobs()

    if op in ("start", "run", "bg"):
        if not command.strip():
            return "ERROR: jobs op=start needs a command."
        jid = "j" + uuid.uuid4().hex[:6]
        log_path = os.path.join(JOBS_DIR, jid + ".log")
        try:
            fp = open(log_path, "wb")
            proc = subprocess.Popen(command, shell=True, cwd=BASE_DIR,
                                    stdin=subprocess.DEVNULL, stdout=fp, stderr=subprocess.STDOUT,
                                    preexec_fn=os.setsid, close_fds=True)
        except Exception as e:
            return f"ERROR starting job: {e}"
        with _jobs_lock:
            _jobs[jid] = {"proc": proc, "log": log_path, "cmd": command,
                          "started": time.time(), "fp": fp}
        _emit(f"$ {command}   (background {jid})")
        return (f"Started {jid} in the background: {command[:120]}\n"
                f"Check with jobs(op=output, job_id={jid}); list with jobs(op=list).")

    if op in ("list", "ls"):
        with _jobs_lock:
            rows = list(_jobs.items())
        if not rows:
            return "No background jobs."
        out = []
        for jid, j in sorted(rows, key=lambda kv: kv[1]["started"]):
            code = j["proc"].poll()
            state = "running" if code is None else f"exit {code}"
            out.append(f"{jid}  {state}  {int(time.time() - j['started'])}s  {j['cmd'][:70]}")
        return "\n".join(out)

    if op in ("output", "out", "log", "status"):
        with _jobs_lock:
            j = _jobs.get(job_id)
        if not j:
            return f"No job {job_id}."
        code = j["proc"].poll()
        state = "still running" if code is None else f"finished, exit {code}"
        try:
            with open(j["log"], encoding="utf-8", errors="replace") as f:
                text = f.read().strip()
        except OSError as e:
            return f"Cannot read the job log: {e}"
        try:
            n = int(tail or 80)
        except (TypeError, ValueError):
            n = 80
        if n > 0:
            text = "\n".join(text.splitlines()[-n:])
        return f"[{job_id}: {state}]\n" + (text or "(no output yet)")

    if op in ("kill", "stop"):
        with _jobs_lock:
            j = _jobs.get(job_id)
        if not j:
            return f"No job {job_id}."
        if j["proc"].poll() is not None:
            return f"{job_id} already finished (exit {j['proc'].returncode})."
        try:
            os.killpg(os.getpgid(j["proc"].pid), signal.SIGTERM)
        except Exception as e:
            return f"ERROR killing {job_id}: {e}"
        return f"Sent SIGTERM to {job_id}."
    return f"Unknown op {op}. Use start, list, output, kill."


def tool_todo(op: str = "list", text: str = "", item_id: str = "", status: str = "",
              items: list | None = None) -> str:
    """The chat's task list: what the job needs and what is done.

    Lives in the chat meta, so it survives a restart and can be shown in the
    app. Use it when a request has three steps or more.
    """
    from store.manager import get_chat_meta, set_chat_meta
    sid = get_current_sid()
    if not sid:
        return "ERROR: no active chat for a todo list."
    meta = get_chat_meta(sid) or {}
    todos = [dict(t) for t in (meta.get("todos") or []) if isinstance(t, dict)]
    op = (op or "list").lower()
    marks = {"done": "[x]", "doing": "[~]", "pending": "[ ]"}

    def render() -> str:
        if not todos:
            return "Todo list is empty."
        done = sum(1 for t in todos if t.get("status") == "done")
        lines = [f"{marks.get(t.get('status', 'pending'), '[ ]')} {t.get('id')} {t.get('text')}"
                 for t in todos]
        return f"Todo ({done}/{len(todos)} done):\n" + "\n".join(lines)

    def save() -> str:
        set_chat_meta(sid, todos=todos)
        return render()

    if op in ("list", "show", "get"):
        return render()
    if op in ("set", "plan"):
        todos = []
        for i, raw in enumerate(items or [], 1):
            if isinstance(raw, dict):
                t = str(raw.get("text") or raw.get("title") or "").strip()
                st = str(raw.get("status") or "pending")
            else:
                t, st = str(raw).strip(), "pending"
            if t:
                todos.append({"id": f"t{i}", "text": t[:200],
                              "status": st if st in ("pending", "doing", "done") else "pending"})
        return save()
    if op == "add":
        if not text.strip():
            return "ERROR: todo add needs text."
        n = len(todos) + 1
        taken = {t.get("id") for t in todos}
        while f"t{n}" in taken:
            n += 1
        todos.append({"id": f"t{n}", "text": text.strip()[:200], "status": "pending"})
        return save()
    if op in ("update", "done", "start", "doing"):
        target = next((t for t in todos if str(t.get("id")) == str(item_id)), None)
        if target is None:
            return f"No todo with id {item_id!r}. Current list:\n{render()}"
        if op == "done":
            target["status"] = "done"
        elif op in ("start", "doing"):
            target["status"] = "doing"
        else:
            if status in ("pending", "doing", "done"):
                target["status"] = status
            if text.strip():
                target["text"] = text.strip()[:200]
        return save()
    if op == "clear":
        todos = []
        return save()
    return f"Unknown op {op!r}. Use set, add, update, done, start, list, clear."


def tool_repo_map(op: str = "find", pattern: str = "", path: str = ".",
                  kind: str = "", limit: int = 40) -> str:
    """The code map: every symbol of a project, by name.

    Tries to answer "where is X" without reading or grepping anything: the
    index is refreshed on demand (only files whose mtime/size changed since
    the last sweep are re-parsed), so an edit made by any other session shows
    up on the next call.
    """
    from store import code_index
    op = (op or "find").strip().lower()
    if op in ("find", "search", "symbol", "lookup"):
        if not pattern:
            return "ERROR: repo_map op=find needs a pattern (a symbol or file name)."
        return code_index.search(pattern, path or ".", kind or "", int(limit or 40))
    if op in ("outline", "file", "list"):
        return code_index.outline(path or ".", int(limit or 200))
    if op in ("refresh", "reindex", "index"):
        changed, note = code_index.refresh(path or ".")
        s = code_index.stats()
        extra = f" ({note})" if note else ""
        return (f"Reindexed {path or '.'}: {changed} file(s) re-parsed{extra}. "
                f"Index now: {s['files']} files, {s['symbols']} symbols, {s['db_bytes'] // 1024} KB.")
    if op in ("stats", "info"):
        s = code_index.stats()
        return (f"Index: {s['files']} files, {s['symbols']} symbols, "
                f"{s['db_bytes'] // 1024} KB — {code_index.DB_PATH}")
    return f"Unknown op {op!r}. Use find, outline, refresh or stats."


def tool_run(path: str = ".", task: str = "", timeout: int = 300) -> str:
    """Build or test a project, picking the command from what is on disk."""
    if not os.path.exists(path):
        return f"Path not found: {path}"
    d = os.path.abspath(path)

    def has(name: str) -> bool:
        return os.path.exists(os.path.join(d, name))

    if has("gradlew"):
        kind, cmd = "Gradle", f"bash gradlew {task or 'assembleDebug'}"
    elif has("package.json"):
        kind, cmd = "npm", f"npm run {task or 'build'}"
    elif has("pyproject.toml") or has("pytest.ini") or has("setup.py") or os.path.isdir(os.path.join(d, "tests")):
        kind, cmd = "pytest", f"python3 -m pytest -q {task}".strip()
    elif has("Makefile"):
        kind, cmd = "make", f"make {task}".strip()
    else:
        return (f"Couldn't tell what kind of project {path} is (no gradlew, package.json, "
                f"pytest config or Makefile). Run the command with shell instead.")
    _emit(f"$ cd {d} && {cmd}")
    out = tool_shell(f"cd {shlex.quote(d)} && {cmd}", timeout=timeout)
    return f"{kind}: {cmd}\n{out}"


def tool_diff_file(path: str, new_content: str) -> str:
    if not os.path.exists(path):
        return "(new file — no diff)"
    with tempfile.NamedTemporaryFile(mode="w", suffix=".new", delete=False) as f:
        f.write(new_content)
        tmp = f.name
    result = tool_shell(f"diff {path} {tmp}")
    os.unlink(tmp)
    return result or "(no differences)"

