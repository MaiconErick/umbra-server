# ─────────────────────────────────────────
DANGEROUS_PATTERNS = [
    r'\brm\s+-rf\b',
    r'\bmkfs\b',
    r'\bdd\s+if=',
    r'\bchmod\s+777\b',
    r'>\s*/dev/sd',
    r'\bwipefs\b',
    r'\bshred\b',
    r'\bfdisk\b',
]

_confirm_callback = None

def set_confirm_callback(fn):
    global _confirm_callback
    _confirm_callback = fn

def _is_dangerous(command: str) -> bool:
    for pattern in DANGEROUS_PATTERNS:
        if re.search(pattern, command):
            return True
    return False

