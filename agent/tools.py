def tool_python(code: str, timeout: int = 60) -> str:
    """Execute Python code. Returns stdout+stderr."""
    env_header = _build_env_header()
    full_code = env_header + "\n" + code

    with tempfile.NamedTemporaryFile(
        mode="w", suffix=".py", dir=TEMP_DIR, delete=False
    ) as f:
        f.write(full_code)
        tmp_path = f.name

    try:
        return tool_shell(f"{sys.executable} {tmp_path}", timeout=timeout)
    finally:
        try:
            os.unlink(tmp_path)
        except Exception:
            pass

def _build_env_header() -> str:
    from dotenv import dotenv_values
    env_path = os.path.join(BASE_DIR, ".env")
    vals = dotenv_values(env_path)
    lines = ["import os"]
    for k, v in vals.items():
        lines.append(f'os.environ.setdefault("{k}", "{v}")')
    return "\n".join(lines)

