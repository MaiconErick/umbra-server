# ─────────────────────────────────────────
#  `say` is mandatory
# ─────────────────────────────────────────
# Every tool carries a `say` parameter (the one-line sentence shown above the
# command bubble in the app). It used to be optional, so models skipped it and
# the app fell back to "Running a command on the Pi: cd /home/pi/... | head"
# — a raw command pasted where a sentence should be. Making it required is the
# only reliable way to get it: optional fields get dropped first when a model
# is in a hurry or the call is near the token limit.
for _t in TOOL_DEFINITIONS:
    _fn = _t.get("function") or {}
    _params = _fn.get("parameters") or {}
    _props = _params.get("properties") or {}
    if "say" in _props:
        _req = _params.setdefault("required", [])
        if "say" not in _req:
            _req.insert(0, "say")

