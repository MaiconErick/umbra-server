# Arguments the dispatcher cannot work without. A model that emits an empty or
# truncated call used to reach args["path"] and raise KeyError, which killed the
# whole turn ("something broke the server 'path'"). Now it is validated before
# dispatch and the model gets an error string it can act on.
REQUIRED_ARGS = {
    "shell":          ("command",),
    "python":         ("code",),
    "write_file":     ("path", "content"),
    "read_file":      ("path",),
    "list_dir":       ("path",),
    "browser":        ("action",),
    "generate_image": ("prompt",),
    "tts":            ("text",),
    "edit_file":      ("path", "old_string"),
    "grep":           ("pattern",),
    "glob":           ("pattern",),
    "repo_map":       ("op",),
    "task":           ("prompt",),
}

# Placeholder values some models send for slots they mean to leave empty.
_NULL_ARGS = ("", None, "null", "None", "none")

# Alternate names models use for the same slot ("file_path" for path, "cmd"
# for command). Filled in before validation, so a guessed key costs nothing
# instead of a whole round trip.
_ARG_ALIASES = {
    "path":    ("file", "file_path", "filename", "filepath", "target"),
    "command": ("cmd", "shell_command", "command_line"),
    "code":    ("source", "script"),
    "content": ("text", "contents", "file_content", "body", "data"),
    "prompt":  ("description", "instructions", "prompt_text", "query"),
    "action":  ("op", "operation"),
    "text":    ("message", "content", "input", "speech"),
    "old_string": ("old", "old_text", "find", "search", "target"),
    "pattern": ("regex", "query", "glob_pattern", "name"),
}


def _empty(value) -> bool:
    return value is None or (isinstance(value, str) and not value.strip())


def _normalize_args(name: str, args: dict) -> dict:
    """Fill required slots from the names models guess instead of ours."""
    out = dict(args)
    for key in REQUIRED_ARGS.get(name, ()):
        if not _empty(out.get(key)):
            continue
        for alt in _ARG_ALIASES.get(key, ()):
            value = args.get(alt)
            if not _empty(value):
                out[key] = value
                break
    return out


def dispatch_tool(name: str, args: dict) -> str:
    """Run a tool. Never raises: any failure comes back as a string the model
    can read and react to, so a bad call can't take the turn down with it.

    Arguments are validated here, before the tool runs, so a KeyError raised
    afterwards can only come from inside the tool: it is logged as a crash
    instead of being blamed on an argument the call did include.
    """
    try:
        name = str(name or "")
        tool = _TOOL_ALIASES.get(name.lower(), name)
        args = _normalize_args(tool, args if isinstance(args, dict) else {})
        # "content" may legitimately be empty (creating an empty file).
        missing = [k for k in REQUIRED_ARGS.get(tool, ())
                   if k not in args or (k != "content" and _empty(args[k]))]
        if missing:
            got = ", ".join(sorted(args)) or "nothing"
            logger.warning("tool %s called without %s (received: %s)", tool, missing, got)
            return (f"ERROR: tool '{tool}' needs {', '.join(missing)} and the call "
                    f"arrived without it (arguments received: {got}). Call it again "
                    f"including {', '.join(missing)}. If the values are huge, split "
                    f"the work into smaller calls.")
        return _dispatch_tool(tool, args)
    except Exception as e:
        logger.exception(f"tool {name} crashed")
        return f"ERROR: tool '{name}' failed: {type(e).__name__}: {e}"


def _dispatch_tool(name: str, args: dict) -> str:
    if name == "shell":
        return tool_shell(args["command"], args.get("timeout") or 120)
    elif name == "python":
        return tool_python(args["code"], args.get("timeout") or 60)
    elif name == "write_file":
        return tool_write_file(args["path"], args["content"])
    elif name == "network":
        from store import netwatch
        return netwatch.tool(args)
    elif name == "read_file":
        return tool_read_file(args["path"], args.get("offset") or 1, args.get("limit") or 0)
    elif name == "list_dir":
        return tool_list_dir(args["path"])
    elif name == "edit_file":
        return tool_edit_file(args["path"], args["old_string"],
                              args.get("new_string") or "", bool(args.get("replace_all")))
    elif name == "grep":
        return tool_grep(args["pattern"], args.get("path") or ".",
                         args.get("include") or "", bool(args.get("ignore_case")),
                         int(args.get("limit") or 60))
    elif name == "glob":
        return tool_glob(args["pattern"], args.get("path") or ".", int(args.get("limit") or 200))
    elif name == "run":
        return tool_run(args.get("path") or ".", args.get("task") or "",
                        int(args.get("timeout") or 300))
    elif name == "repo_map":
        return tool_repo_map(args.get("op") or "find", args.get("pattern") or "",
                             args.get("path") or ".", args.get("kind") or "",
                             int(args.get("limit") or 40))
    elif name == "todo":
        return tool_todo(args.get("op") or "list", args.get("text") or "",
                         str(args.get("item_id") or ""), args.get("status") or "",
                         args.get("items") or [])
    elif name == "jobs":
        return tool_jobs(args.get("op") or "list", args.get("command") or "",
                         str(args.get("job_id") or ""), int(args.get("tail") or 80))
    elif name == "browser":
        return tool_browser(
            args["action"], args.get("url", ""),
            args.get("selector", ""), args.get("text", ""),
            args.get("wait", 3)
        )
    elif name == "generate_image":
        refs = args.get("_refs") or []
        out = tool_generate_image(args["prompt"],
                                  args.get("provider"),
                                  args.get("model"), refs)
        _note_refs(len(refs))
        _img_done(out)
        return out
    elif name == "tts":
        return tool_tts(args["text"], args.get("provider"))
    elif name == "system_snapshot":
        return tool_system_snapshot()
    return f"Unknown tool: {name}"